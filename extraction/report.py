"""Write data/conditions/SUMMARY.md and data/conditions/REVIEW.md from the built records.

Both files are generated: edit the adapters, the document records or the reasons below,
then re-run extraction/build_conditions.py.
"""
from __future__ import annotations

import csv
from collections import Counter, defaultdict
from pathlib import Path

from common import OUT_DIR, REPO
from tables import adapters

INVESTIGATIONS = REPO / "data" / "manifest" / "investigations.csv"

CORE = ["gravity_regime", "fuel_phase", "diluent", "flame_type", "o2_mole_fraction",
        "burner_o2_mole_fraction", "pressure", "flow_velocity", "sample_thickness",
        "droplet_diameter_initial", "ambient_temperature", "fuel", "material", "flow_configuration",
        "platform"]
SHORT = {"gravity_regime": "gravity", "fuel_phase": "phase", "diluent": "diluent", "flame_type": "flame",
         "o2_mole_fraction": "O2", "burner_o2_mole_fraction": "burner O2", "pressure": "p",
         "flow_velocity": "flow", "sample_thickness": "thick.", "droplet_diameter_initial": "d0",
         "ambient_temperature": "T", "fuel": "fuel", "material": "material",
         "flow_configuration": "flow cfg", "platform": "platform"}

# Why an investigation has no usable condition records, or only a few. Factual, checked
# against the files in data/raw/ on 2026-11-14. Shown in SUMMARY.md.
LIMITS = {
    "PSI-47": "DAFT / DAFT-2 tested aerosol instruments with Arizona Road Dust in ISS nitrogen: no flame, "
              "so there is no combustion condition to extract. Its table lists hardware, dust and "
              "sampling location only.",
    "PSI-142": "Ground investigation. Its experimental table is a list of figures in a published paper "
               "(data ID, description, DOI, figure number), not test conditions.",
    "PSI-60": "Ground (computational) investigation with a single metadata archive in PSI; no "
              "experimental table or document with test conditions.",
    "PSI-62": "Ground (computational) investigation with a single metadata archive in PSI; no "
              "experimental table or document with test conditions.",
}


def _names():
    with INVESTIGATIONS.open(encoding="utf-8", newline="") as fh:
        return {r["accession"]: r for r in csv.DictReader(fh)}


def _usable(r):
    return r["status"] in ("extracted", "verified")


def write(by_acc, skipped, sources):
    inv = _names()
    order = sorted(inv, key=lambda a: int(a.split("-")[1]))
    interp = {m.ACCESSION: getattr(m, "INTERPRETATIONS", []) for m in adapters()}
    _summary(by_acc, skipped, inv, order, interp)
    _review(by_acc, inv, order, interp)


def _summary(by_acc, skipped, inv, order, interp):
    L = []
    total = sum(len(v) for v in by_acc.values())
    usable = sum(1 for v in by_acc.values() for r in v if _usable(r))
    L += ["# Condition records: summary", "",
          "Generated by `extraction/build_conditions.py`; do not edit by hand.", "",
          f"**{total} records** in `data/conditions/` for {sum(1 for a in order if by_acc.get(a))} of the "
          f"{len(order)} PSI combustion investigations: {usable} usable (`extracted` or `verified`), "
          f"{total - usable} `insufficient_evidence`.", "",
          "- `table` records are read by code from a PSI experimental table: the quote is the column header.",
          "- `document` records carry the verbatim sentence from a PSI record or document; every one is "
          "listed in [`REVIEW.md`](REVIEW.md) for a human check.",
          "- No record is `verified` yet: `verified` means a person compared it with the source.", ""]

    L += ["## Usable records per investigation and axis", "",
          "Counts of `extracted` + `verified` records. Outcomes (`outcome:*`) are counted together.", ""]
    head = ["Investigation"] + [SHORT[v] for v in CORE] + ["outcomes", "insufficient"]
    L += ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for a in order:
        recs = by_acc.get(a, [])
        c = Counter(r["variable"] for r in recs if _usable(r))
        outc = sum(n for v, n in c.items() if v.startswith("outcome:"))
        ins = sum(1 for r in recs if r["status"] == "insufficient_evidence")
        name = inv[a]["acronym"] or "(ground)"
        cells = [f"{a} {name}"] + [str(c.get(v, "")) for v in CORE] + [str(outc or ""), str(ins or "")]
        L.append("| " + " | ".join(cells) + " |")
    L.append("")

    L += ["## Investigations with no usable conditions, or only partial ones", ""]
    for a in order:
        recs = by_acc.get(a, [])
        if a in LIMITS:
            L.append(f"- **{a} {inv[a]['acronym'] or inv[a]['title']}**: {LIMITS[a]}")
        elif not recs:
            L.append(f"- **{a} {inv[a]['acronym'] or inv[a]['title']}**: not extracted yet.")
    L.append("")

    L += ["## Table readings that rely on a judgement", "",
          "Each of these is applied by code, the same way to every row, and is also listed in "
          "[`REVIEW.md`](REVIEW.md).", ""]
    for a in order:
        for item in interp.get(a, []):
            L.append(f"- **{a}**: {item}")
    L.append("")

    L += ["## `insufficient_evidence` records", "",
          "Grouped by investigation, variable and reason. Consumers skip these as evidence.", ""]
    groups = defaultdict(list)
    for a in order:
        for r in by_acc.get(a, []):
            if r["status"] == "insufficient_evidence":
                groups[(a, r["variable"], r["note"])].append(r["test_id"])
    if not groups:
        L.append("None.")
    for (a, var, note), tids in groups.items():
        shown = ", ".join(tids[:12]) + (f", ... ({len(tids)} in all)" if len(tids) > 12 else "")
        L.append(f"- **{a}** `{var}` ({len(tids)}): {note}. Tests: {shown}")
    L.append("")

    L += ["## Cells not turned into records", "",
          "Non-empty cells of a mapped column that hold no number the adapter can read. The full list, "
          "cell by cell, is `extraction/skipped_cells.csv`.", ""]
    agg = Counter((s["accession"], s["column"], s["reason"]) for s in skipped)
    if not agg:
        L.append("None.")
    for (a, col, why), n in sorted(agg.items(), key=lambda x: (int(x[0][0].split('-')[1]), x[0][1])):
        L.append(f"- **{a}** column `{col}`: {n} cells ({why})")
    L.append("")
    (OUT_DIR / "SUMMARY.md").write_text("\n".join(L), encoding="utf-8")


def _review(by_acc, inv, order, interp):
    L = ["# Records to check by reading", "",
         "Generated by `extraction/build_conditions.py`; do not edit by hand.", "",
         "For each record below, open the file at the location given and check that the quoted "
         "sentence is there and says the value we wrote. Nothing here needs combustion expertise: "
         "it is a comparison between our row and NASA's words. Paths are relative to `data/raw/`.", ""]
    n_doc = 0
    for a in order:
        docs = [r for r in by_acc.get(a, []) if r["method"] == "document"]
        items = interp.get(a, [])
        if not docs and not items:
            continue
        L += [f"## {a} {inv[a]['acronym'] or inv[a]['title']}", ""]
        for item in items:
            L.append(f"- *Table reading:* {item}")
        if items:
            L.append("")
        for r in docs:
            n_doc += 1
            unit = f" {r['unit']}" if r["unit"] else ""
            L += [f"### {r['variable']} = {r['value']}{unit}  (test `{r['test_id']}`, {r['status']})", "",
                  f"> {r['quote']}", "",
                  f"- File: `{r['source_file']}`",
                  f"- Location: `{r['source_location']}`",
                  f"- As written: `{r['value_original']}`" + (f" ({r['unit_original']})" if r["unit_original"] else "")]
            if r["note"]:
                L.append(f"- Note: {r['note']}")
            L.append("")
    if n_doc == 0:
        L += ["No document records yet.", ""]
    (OUT_DIR / "REVIEW.md").write_text("\n".join(L), encoding="utf-8")
