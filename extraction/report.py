def _names():
    with INVESTIGATIONS.open(encoding="utf-8", newline="") as fh:
        return {r["accession"]: r for r in csv.DictReader(fh)}


def _d(x: Decimal) -> str:
    return format(x.normalize() if x == x.to_integral() else x, "f") if abs(x) < 10 ** 6 else str(x)


def _usable(r):
    return r["status"] in ("extracted", "verified")


def write(by_acc, skipped, sources, doc_stats=None):
    inv = _names()
    order = sorted(inv, key=lambda a: int(a.split("-")[1]))
    interp = {m.ACCESSION: getattr(m, "INTERPRETATIONS", []) for m in adapters()}
    _summary(by_acc, skipped, inv, order, interp, doc_stats or {})
    _review(by_acc, inv, order, interp)


def _summary(by_acc, skipped, inv, order, interp, doc_stats):
    L = []
    total = sum(len(v) for v in by_acc.values())
    usable = sum(1 for v in by_acc.values() for r in v if _usable(r))
    L += ["# Condition records: summary", "",
          "Generated by `extraction/build_conditions.py`; do not edit by hand.", "",
          f"**{total} records** in `data/conditions/` for {sum(1 for a in order if by_acc.get(a))} of the "
          f"{len(order)} PSI combustion investigations: {usable} usable (`extracted` or `verified`), "
          f"{total - usable} `insufficient_evidence`.", "",
          "- `table` records are read by code from a PSI experimental table: the quote is the column header.",
          "- `document` records carry the verbatim sentence from a PSI record or document; every one is "
          "listed in [`REVIEW.md`](REVIEW.md) for a human check.",
          "- No record is `verified` yet: `verified` means a person compared it with the source.", ""]

    L += ["## Usable records per investigation and axis", "",
          "Counts of `extracted` + `verified` records. Outcomes (`outcome:*`) are counted together.", ""]
    head = ["Investigation"] + [SHORT[v] for v in CORE] + ["outcomes", "insufficient"]
    L += ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for a in order:
        recs = by_acc.get(a, [])
        c = Counter(r["variable"] for r in recs if _usable(r))
        outc = sum(n for v, n in c.items() if v.startswith("outcome:"))
        ins = sum(1 for r in recs if r["status"] == "insufficient_evidence")
        name = inv[a]["acronym"] or "(ground)"
        cells = [f"{a} {name}"] + [str(c.get(v, "")) for v in CORE] + [str(outc or ""), str(ins or "")]
        L.append("| " + " | ".join(cells) + " |")
    L.append("")

    L += ["## Measured ranges (usable records)", "",
          "Lowest and highest value per investigation and continuous axis, over `extracted` + `verified` "
          "records (ranges `lo..hi` contribute both ends). This is a summary, not an envelope: "
          "the engine builds envelopes from the individual records.", ""]
    axes = ["o2_mole_fraction", "burner_o2_mole_fraction", "pressure", "flow_velocity", "sample_thickness",
            "droplet_diameter_initial", "ambient_temperature"]
    units = {"o2_mole_fraction": "", "burner_o2_mole_fraction": "", "pressure": " kPa", "flow_velocity": " cm/s",
             "sample_thickness": " mm", "droplet_diameter_initial": " mm", "ambient_temperature": " K"}
    L += ["| Investigation | " + " | ".join(SHORT[a] + units[a] for a in axes) + " |", "|" + "---|" * (len(axes) + 1)]
    for a in order:
        rng = {}
        for r in by_acc.get(a, []):
            if not _usable(r) or r["variable"] not in axes:
                continue
            try:
                parts = [Decimal(x) for x in r["value"].split("..")]
            except InvalidOperation:
                continue
            lo, hi = min(parts), max(parts)
            old_lo, old_hi = rng.get(r["variable"], (lo, hi))
            rng[r["variable"]] = (min(old_lo, lo), max(old_hi, hi))
        if rng:
            cells = [f"{_d(rng[x][0])}-{_d(rng[x][1])}" if x in rng and rng[x][0] != rng[x][1]
                     else (_d(rng[x][0]) if x in rng else "") for x in axes]
            L.append(f"| {a} {inv[a]['acronym'] or '(ground)'} | " + " | ".join(cells) + " |")
    L.append("")

    L += ["## Investigations with no usable conditions, or only partial ones", ""]
    for a in order:
        recs = by_acc.get(a, [])
        if a in LIMITS:
            L.append(f"- **{a} {inv[a]['acronym'] or inv[a]['title']}**: {LIMITS[a]}")
        elif not recs:
            L.append(f"- **{a} {inv[a]['acronym'] or inv[a]['title']}**: not extracted yet.")
    L.append("")

    L += ["## Investigations with no usable `gravity_regime` record", "",
          "The engine reads these as INSUFFICIENT_EVIDENCE for gravity. A gravity record is kept only when a source sentence "
          "states the gravity condition of the tests; the platform (ISS, Cygnus) is never used for it. Investigations with "
          "records but none usable:", ""]
    missing = [a for a in order if by_acc.get(a) and not any(
        r["variable"] == "gravity_regime" and _usable(r) for r in by_acc[a])]
    for a in missing:
        L.append(f"- **{a} {inv[a]['acronym'] or inv[a]['title']}**: " + GRAVITY_NOTES.get(
            a, "no source sentence found that states the gravity condition of the tests."))
    if not missing:
        L.append("None.")
    L.append("")
    L += ["Partial coverage (a gravity record exists for some tests only):", ""]
    for a, note in GRAVITY_PARTIAL.items():
        if by_acc.get(a):
            L.append(f"- **{a} {inv[a]['acronym'] or inv[a]['title']}**: {note}")
    L.append("")
    L += ["## Document extraction: extractor, then verificador", "",
          "For each investigation, an extractor agent proposed records with verbatim quotes "
          "(`extraction/documents/review/<ACC>.extractor.json`); a verificador agent, in a separate run that did not see "
          "the extractor's reasoning, tried to break each one (`<ACC>.verificador.json`). Only KEEP and MODIFY records are "
          "ingested; `ambiguous` confidence becomes `insufficient_evidence`. `diluent` is the inert gas of the ambient, so "
          "statements about the gas inside a burner stream are not ingested as `diluent`. Records whose test_id names no test of the PSI "
          "table (planned test-matrix numbers, a paper's own numbering, ground tests outside PSI) are not ingested. This is a "
          "segregated internal check by language models, not expert or NASA review.", "",
          "| Investigation | proposed | KEEP | MODIFY | REJECT | not in PSI tables | burner-stream diluent | ingested | awaiting verification |",
          "|---|---|---|---|---|---|---|---|---|"]
    for a in order:
        st = doc_stats.get(a)
        if not st:
            continue
        L.append(f"| {a} {inv[a]['acronym'] or '(ground)'} | {st.get('proposed', 0)} | {st.get('keep', 0)} | "
                 f"{st.get('modify', 0)} | {st.get('reject', 0)} | {st.get('outside_psi_tables', 0)} | "
                 f"{st.get('burner_stream_diluent', 0)} | "
                 f"{st.get('ingested', 0)} | {st.get('awaiting_verification', 0)} |")
    L.append("")
    L += ["## Rules applied to every table", "",
          "- A test condition is the state **before or at the start** of the test. Readings taken after the test "
          "(\"XO2 after test\", \"XO2 (final)\", \"pfinal\", \"Calibrated final O2\") are kept as outcomes "
          "(`outcome:o2_mole_fraction_after_test`, `outcome:pressure_after_test`), never as points on a condition axis: "
          "a final reading can follow suppression or extinction (BASS-II final O2 goes down to 0.6 %).",
          "- Cells that say there is no single value (en dash, `RAMP`, `RAMPED`, `LOW O2`, `n/a`, spreadsheet errors) "
          "give no record and are listed in `extraction/skipped_cells.csv`.",
          "- Unit conversions use exact factors (mmHg x 101.325/760, atm x 101.325, bar x 100, percent x 0.01, "
          "micron x 0.001, C + 273.15); a converted value longer than 6 significant digits is rounded to 6, and the "
          "record's note says so.", ""]
    L += ["## Table readings that rely on a judgement", "",
          "Each of these is applied by code, the same way to every row, and is also listed in "
          "[`REVIEW.md`](REVIEW.md).", ""]
    for a in order:
        for item in interp.get(a, []):
            L.append(f"- **{a}**: {item}")
    L.append("")

    L += ["## `insufficient_evidence` records", "",
          "Grouped by investigation, variable and reason. Consumers skip these as evidence.", ""]
    groups = defaultdict(list)
    for a in order:
        for r in by_acc.get(a, []):
            if r["status"] == "insufficient_evidence":
                groups[(a, r["variable"], r["note"])].append(r["test_id"])
    if not groups:
        L.append("None.")
    for (a, var, note), tids in groups.items():
        shown = ", ".join(tids[:12]) + (f", ... ({len(tids)} in all)" if len(tids) > 12 else "")
        L.append(f"- **{a}** `{var}` ({len(tids)}): {note}. Tests: {shown}")
    L.append("")

    L += ["## Cells not turned into records", "",
          "Non-empty cells of a mapped column that hold no number the adapter can read. The full list, "
          "cell by cell, is `extraction/skipped_cells.csv`.", ""]
    agg = Counter((s["accession"], s["column"], s["reason"]) for s in skipped)
    if not agg:
        L.append("None.")
    for (a, col, why), n in sorted(agg.items(), key=lambda x: (int(x[0][0].split('-')[1]), x[0][1])):
        L.append(f"- **{a}** column `{col}`: {n} cells ({why})")
    L.append("")
    (OUT_DIR / "SUMMARY.md").write_text("\n".join(L), encoding="utf-8")


def _review(by_acc, inv, order, interp):
    L = ["# Records to check by reading", "",
         "Generated by `extraction/build_conditions.py`; do not edit by hand.", "",
         "For each record below, open the file at the location given and check that the quoted "
         "sentence is there and says the value we wrote. Nothing here needs combustion expertise: "
         "it is a comparison between our row and NASA's words. Paths are relative to `data/raw/`. One entry per "
         "statement; a statement that covers several tests is listed once with the tests it applies to.", ""]
    n_doc = 0
    for a in order:
        docs = [r for r in by_acc.get(a, []) if r["method"] == "document"]
        items = interp.get(a, [])
        if not docs and not items:
            continue
        L += [f"## {a} {inv[a]['acronym'] or inv[a]['title']}", ""]
        for item in items:
            L.append(f"- *Table reading:* {item}")
        if items:
            L.append("")
        groups = {}
        for r in docs:
            key = (r["variable"], r["value"], r["unit"], r["quote"], r["source_file"], r["source_location"],
                   r["status"], r["value_original"], r["unit_original"], r["note"])
            groups.setdefault(key, []).append(r["test_id"])
        for (var, val, unit, quote, sf, loc, status, vo, uo, note), tids in groups.items():
            n_doc += 1
            u = f" {unit}" if unit else ""
            tests = "all tests (`*`)" if tids == ["*"] else (
                f"{len(tids)} tests: " + ", ".join(f"`{t}`" for t in tids[:15]) + (" ..." if len(tids) > 15 else ""))
            L += [f"### {var} = {val}{u}  ({status})", "",
                  f"> {quote}", "",
                  f"- File: `{sf}`",
                  f"- Location: `{loc}`",
                  f"- As written: `{vo}`" + (f" ({uo})" if uo else ""),
                  f"- Applies to: {tests}"]
            if note:
                L.append(f"- Note: {note}")
            L.append("")
    if n_doc == 0:
        L += ["No document records yet.", ""]
    (OUT_DIR / "REVIEW.md").write_text("\n".join(L), encoding="utf-8")
